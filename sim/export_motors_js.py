#!/usr/bin/env python3
"""Writes web/motors-data.js from motors/motors.json + .eng curves, so the browser uses the exact
same thrust curves and masses as the Python sim (MIT licence). Run after adding a motor."""
import json, pathlib
import phase0_compare as pc
HERE = pathlib.Path(__file__).resolve().parent
meta = json.load(open(HERE / "motors" / "motors.json"))["motors"]
out = {}
for k, m in meta.items():
    mot = pc.load_motor(k, k)
    out[k] = {"name": k, "curve": [[round(t, 6), round(f, 6)] for t, f in mot.curve], "mp": mot.prop_mass, "mt": mot.total_mass,
              "cert_org": m["record"].get("cert_org", ""), "type": m.get("type", "single-use"), "simfile": m["simfile_page"], "delays_s": m.get("delays_s", [])}
js = ("// GENERATED by sim/export_motors_js.py from sim/motors (ThrustCurve.org). Do not edit by hand.\n"
      "var MOTOR_DATA=" + json.dumps(out, separators=(",", ":")) + ";\n"
      "if(typeof module!=='undefined')module.exports=MOTOR_DATA;\n")
(HERE.parent / "web" / "motors-data.js").write_text(js)
print(f"wrote {len(out)} motors")
